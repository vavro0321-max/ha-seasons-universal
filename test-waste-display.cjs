'use strict';
const fs=require('fs'),vm=require('vm'),assert=require('assert');
const code=fs.readFileSync(__dirname+'/dist/ha-seasons-universal.js','utf8')
  .replace("const ASSETS=new URL('./assets/',import.meta.url).href;","const ASSETS='/assets/';");
const context={window:{customCards:[]},customElements:{get:()=>undefined,define:()=>{}},
  HTMLElement:class{},Date,Intl,URL,Math,console,devicePixelRatio:1};
vm.createContext(context);
vm.runInContext(code+
  "\nglobalThis.wasteTests={wasteDateInfo,wasteInfoFromEntity,wasteEntries,HASeasonsUniversalCard};",context);
const {wasteDateInfo,wasteInfoFromEntity,wasteEntries,HASeasonsUniversalCard}=context.wasteTests;
const today={year:2026,month:11,day:21,hour:21};
const municip='sensor.najblizsi_komunalny_odpad';
const recycling='sensor.najblizsi_triedeny_zber';
const state=value=>({state:value,attributes:{}});
const none={states:{},config:{time_zone:'Europe/Bratislava'}};
assert.equal(wasteEntries(none,{},today).length,0,'Must hide waste for other HA users with no waste sensors');
assert.equal(wasteEntries(none,{show_waste:true},today).length,0,'Opt in does not create fake dates');
assert.equal(wasteEntries(none,{show_waste:false},today).length,0);
const both={states:{[municip]:state('2026-11-22'),[recycling]:state('23.11.2026')}};
const entries=wasteEntries(both,{},today);
assert.equal(entries.length,2,'Auto-discover both known sensors');
assert.equal(entries[0].kind,'municipal');
assert.equal(entries[1].kind,'recycling');
assert.equal(entries[0].days,1);
assert.equal(entries[0].short,'ZAJTRA');
assert.equal(entries[0].urgent,true);
assert.equal(entries[1].days,2);
assert.equal(entries[1].urgent,false);
assert.equal(wasteEntries(both,{show_waste:false},today).length,0,'Manual toggle hides even with sensors');
assert.equal(wasteEntries({states:{[municip]:state('unknown')}},{},today).length,0);
assert.equal(wasteEntries({states:{[municip]:state('unavailable')}},{},today).length,0);
assert.equal(wasteEntries({states:{[municip]:state('2026-11-20')}},{},today).length,0,'Old collection dates hidden');
assert.equal(wasteEntries({states:{[municip]:state('2026-11-21')}},{},today)[0].short,'DNES');
assert.equal(wasteEntries({states:{[municip]:state('2026-11-22T00:00:00+01:00')}},{},today)[0].days,1,'No UTC shift for local pickup date');
assert.equal(wasteDateInfo('2026-02-29',today),null,'Reject impossible dates');
assert.equal(wasteDateInfo('invalid date',today),null);
assert.equal(wasteDateInfo('unknown',today),null);
assert.equal(wasteDateInfo('2027-11-23',today),null,'Do not present a date more than a year away');
assert.equal(wasteDateInfo('0',today).days,0,'Day countdown today');
assert.equal(wasteDateInfo('2',today).days,2,'Relative countdown accepted');
assert.equal(wasteDateInfo('2027-01-01',{year:2026,month:12,day:31}).days,1,'Crossing the year');
const leap=wasteDateInfo('29.02.2028',{year:2028,month:2,day:28});
assert.equal(leap.days,1,'Leap day');
const alt={states:{'sensor.my_waste':state('2026-11-24')}};
assert.equal(wasteEntries(alt,{},today).length,0,'Generic sensor should not be mistaken for a waste sensor');
assert.equal(wasteEntries(alt,{entities:{waste_municipal:'sensor.my_waste'}},today)[0].days,3,'User can select their own sensor');
assert.equal(wasteEntries(both,{entities:{waste_municipal:'sensor.missing'}},today).length,1,'Explicit missing municipal sensor must not fall back and mislead');
assert.equal(wasteInfoFromEntity({state:'unknown',attributes:{next_date:'2026-11-26'}},today).days,5,'Support attributes');
assert.equal(wasteEntries({states:{'sensor.separovana_nadoba':state('2026-11-23')}},{},today).length,1,'Generic recycling detection');
assert(code.includes('data-waste="municipal"')&&code.includes('data-waste="recycling"'),'Both visual cards exist');
assert(code.includes("wasteBar.style.display=waste.length?'grid':'none'"),'Empty waste row must disappear');
assert(code.includes("show_waste:'Zobrazovať vývoz odpadu"),'Editor master toggle');
assert(code.includes("waste_municipal:'Komunálny odpad"),'Editor optional municipal entity');
assert(code.includes("waste_recycling:'Separovaný odpad"),'Editor optional recycling entity');
const card=Object.create(HASeasonsUniversalCard.prototype);
card.setConfig({idle_seconds:30,source:'auto'});
assert.equal(card._config.show_waste,true);
assert(!code.includes('livingPaintActor')&&!code.includes('canvas class="livingfx"'),'No unwanted people/cars overlay');
assert(code.includes('contrast(')&&code.includes('nightContrast.toFixed(3)'),'Night visibility must lift deep shadows');
assert(code.includes('const nightContrast=1-.07*d.nightLight;'),'Night contrast stays close to natural levels to avoid washed-out haze');
console.log('PASS optional municipal/recycling pickup, valid local dates, missing sensors, UI and improved night visibility');
